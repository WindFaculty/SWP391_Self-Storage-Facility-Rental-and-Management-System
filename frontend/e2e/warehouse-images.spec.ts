import { test, expect } from '@playwright/test'
import path from 'node:path'

// Run against a backend with the local demo seed and an isolated database:
// MEDIA_E2E=1 npx playwright test e2e/warehouse-images.spec.ts
test.skip(process.env.MEDIA_E2E !== '1', 'Requires a running backend with the local demo seed')
const small = path.resolve('public/images/unit-types/small.jpg')
const medium = path.resolve('public/images/unit-types/medium.jpg')

async function login(page: import('@playwright/test').Page, email: string) {
  const csrf = await page.request.get('/api/v1/auth/cookie/csrf')
  expect(csrf.ok()).toBe(true)
  const login = await page.request.post('/api/v1/auth/cookie/login', {
    headers: { 'X-XSRF-TOKEN': (await csrf.json()).data.token },
    data: { email, password: '123' },
  })
  expect(login.ok()).toBe(true)
}

test('manager uploads, edits and clears unit and facility photos; customers view the galleries', async ({ page }) => {
  await login(page, 'thien@gmail.com')
  await page.goto('/facility/units')
  await page.getByRole('button', { name: 'Thêm kho mới', exact: true }).click()
  const code = 'IMG-' + Date.now().toString().slice(-9)
  await page.getByLabel('Mã định danh kho').fill(code)
  await page.locator('#unit-type').selectOption({ label: 'Kho nhỏ (5 m²)' })
  await page.getByLabel('Vị trí / Tầng').fill('Tầng 1')
  await page.getByLabel('Giá thuê niêm yết').fill('650000')
  await page.getByLabel('Thêm ảnh từ máy').setInputFiles([small, medium])
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(2)
  await page.getByRole('button', { name: 'Đặt đại diện' }).click()
  const createdResponse = page.waitForResponse(response => response.url().endsWith('/api/v1/ops/units') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Tạo kho', exact: true }).click()
  const created = await createdResponse
  expect(created.ok()).toBe(true)
  const unit = (await created.json()).data
  expect(unit.images).toHaveLength(2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await page.locator('#unit-search').fill(code)
  await page.getByRole('row').filter({ hasText: code }).getByRole('button', { name: 'Chi tiết' }).click()
  await expect(page.getByRole('img', { name: `Hình ảnh kho ${code}` })).toBeVisible()
  await page.getByRole('button', { name: 'Sửa thông tin kho' }).click()
  await page.getByRole('button', { name: 'Xóa ảnh 1', exact: true }).click()
  const updatedResponse = page.waitForResponse(response => response.url().endsWith(`/api/v1/ops/units/${unit.id}`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  expect((await updatedResponse).ok()).toBe(true)
  await expect.poll(async () => (await page.request.get(`/api/v1/facilities/${unit.facilityId}/units?size=48`)).json()
    .then(body => body.data.content.find((item: { id: number }) => item.id === unit.id)?.images.length)).toBe(1)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Ảnh cơ sở', exact: true }).click()
  await page.getByLabel('Thêm ảnh từ máy').setInputFiles(small)
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(2)
  await page.getByRole('button', { name: 'Đặt đại diện' }).click()
  const facilityResponse = page.waitForResponse(response => response.url().endsWith(`/api/v1/ops/facilities/${unit.facilityId}/images`) && response.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Lưu bộ ảnh' }).click()
  expect((await facilityResponse).ok()).toBe(true)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/warehouse-images-manager.png', fullPage: true })

  await page.context().clearCookies()
  await page.goto(`/facilities/${unit.facilityId}`)
  await expect(page.getByRole('heading', { name: 'Ảnh từng kho' })).toBeVisible()
  await expect(page.getByRole('heading', { name: `Kho ${code}`, exact: true })).toBeVisible()
  const hero = page.getByRole('img', { name: 'Hình ảnh Kho tự quản Gò Vấp', exact: true })
  await expect.poll(() => hero.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0)
  await page.screenshot({ path: 'test-results/warehouse-images-customer.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'test-results/warehouse-images-mobile.png', fullPage: true })

  await login(page, 'thien@gmail.com')
  await page.goto('/facility/units')
  await page.getByRole('button', { name: 'Ảnh cơ sở', exact: true }).click()
  await page.getByRole('button', { name: 'Xóa ảnh 1', exact: true }).click()
  await page.getByRole('button', { name: 'Xóa ảnh 1', exact: true }).click()
  await page.getByRole('button', { name: 'Lưu bộ ảnh' }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Ảnh cơ sở', exact: true }).click()
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Hủy', exact: true }).click()
})

test('admin creates and edits a facility with photos', async ({ page }) => {
  await login(page, 'admin@gmail.com')
  await page.goto('/operations/facilities')
  await page.getByRole('button', { name: 'Thêm cơ sở mới' }).click()
  const code = 'PHOTO-' + Date.now().toString().slice(-9)
  await page.getByLabel('Mã cơ sở').fill(code)
  await page.getByLabel('Tên cơ sở').fill('Cơ sở thử ảnh')
  await page.getByLabel('Địa chỉ').fill('Địa chỉ thử nghiệm')
  await page.getByLabel('Thêm ảnh từ máy').setInputFiles([small, medium])
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(2)
  const response = page.waitForResponse(response => response.url().endsWith('/api/v1/management/facilities') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Tạo cơ sở', exact: true }).click()
  expect((await response).ok()).toBe(true)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('row').filter({ hasText: code }).getByRole('button', { name: 'Sửa', exact: true }).click()
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(2)
  await page.getByRole('button', { name: 'Xóa ảnh 1', exact: true }).click()
  await page.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('row').filter({ hasText: code }).getByRole('button', { name: 'Sửa', exact: true }).click()
  await expect(page.getByRole('img', { name: /Ảnh xem trước/ })).toHaveCount(1)
})
